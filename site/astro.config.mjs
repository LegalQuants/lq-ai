// @ts-check
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { satteri } from '@astrojs/markdown-satteri';

import { EDIT_BASE } from './src/repo.mjs';
import { NAMESPACES } from './src/namespaces.mjs';
import { rehypeLqTablesSatteri } from './scripts/lib/rehype-lq-tables.mjs';
/**
 * Deployment target. Both are configuration, never content (ADR 0028): no page
 * source, link rewrite, or generated absolute URL may hard-code `/lq-ai/`.
 * Moving the site to a custom domain is `SITE_URL` + `SITE_BASE` and a rebuild.
 *
 * The two defaults live in `scripts/lib/paths.mjs` and are imported here, so
 * Astro and the build scripts cannot drift apart: the sync writes links with
 * the same base Astro serves them under.
 */
import { SITE_BASE, SITE_URL } from './scripts/lib/paths.mjs';

/**
 * `autogenerate` throws when its directory does not exist, and the content
 * collection is generated by `npm run sync` from whatever `docs/site/` holds
 * today — which is a partial tree while the site is being written. Groups are
 * therefore filtered to the namespaces that actually produced pages. The fixed
 * order in `src/namespaces.mjs` is preserved; nothing is reordered or invented.
 *
 * `npm run sync` always runs before `astro build` and `astro dev`, so the tree
 * this reads is the one the build is about to use. A namespace's first page
 * needs one restart of a long-running dev server to appear in the sidebar.
 */
const contentDir = fileURLToPath(new URL('./src/content/docs/', import.meta.url));
const sidebar = NAMESPACES.filter(({ dir }) => existsSync(contentDir + dir)).map(
  ({ label, dir }) => ({
    label,
    // Starlight 0.39 removed `label` on an `autogenerate` object: a named group
    // wraps the autogenerate item instead. Nested directories (operate/recipes/,
    // skills/coverage/) become nested groups automatically; within a group
    // Starlight orders by `sidebar.order` then title, which is the ordering the
    // authoring contract promises.
    items: [{ autogenerate: { directory: dir } }],
  })
);

export default defineConfig({
  site: SITE_URL,
  base: SITE_BASE,
  // Every internal URL ends in `/`; `directory` format writes `<route>/index.html`.
  // The machine surface hangs `<route>.md` off the same route strings.
  trailingSlash: 'always',
  build: { format: 'directory' },
  markdown: {
    // Astro 7's default Markdown processor. `markdown.rehypePlugins` is not a
    // config option under it (that option belongs to the legacy
    // `@astrojs/markdown-remark` processor, not installed here — adding it
    // would be a new dependency). Sätteri's own extension point is
    // `hastPlugins`: `rehypeLqTablesSatteri` renders each Markdown table by
    // its content's shape (definition list / records / grid) instead of as a
    // generic wide `<table>` — see `scripts/lib/rehype-lq-tables.mjs`.
    processor: satteri({ hastPlugins: [rehypeLqTablesSatteri()] }),
  },
  integrations: [
    starlight({
      title: 'LQ.AI',
      description:
        'Documentation for LQ.AI — a self-hosted, bring-your-own-keys AI platform for in-house legal teams.',
      // The site's own theme. No webfonts: a trust centre makes no third-party
      // requests to render a page.
      customCss: ['./src/styles/theme.css'],
      // The site stamps every page with the commit it was checked against
      // (Footer.astro), which is a stronger claim than a file mtime. Starlight's
      // own "last updated" would show a second, weaker date beside it.
      lastUpdated: false,
      pagination: true,
      editLink: { baseUrl: EDIT_BASE },
      favicon: '/favicon.svg',
      head: [
        {
          tag: 'meta',
          attrs: { name: 'color-scheme', content: 'light dark' },
        },
      ],
      expressiveCode: {
        /**
         * Code blocks wrap instead of scrolling sideways.
         *
         * A horizontally scrollable region has to be reachable by keyboard
         * (WCAG 2.1.1; axe `scrollable-region-focusable`), and Expressive Code's
         * `<pre>` is not focusable — so any code block wider than the content
         * column failed the accessibility gate. Wrapping removes the scroll
         * region rather than papering over it, and it does so for every code
         * block the site will ever contain, not just the ones written so far.
         * `preserveIndent` keeps a continuation line aligned under its own
         * indentation, and the copy button still copies the unwrapped source.
         */
        defaultProps: { wrap: true, preserveIndent: true },
      },
      // Search is Starlight's built-in Pagefind: a static index built at build
      // time and served from this origin (ADR 0028 decision 5). No hosted search
      // service receives a reader's query.
      pagefind: true,
      // "Built with Starlight" is off; the footer carries the project's own line.
      credits: false,
      components: {
        Header: './src/components/Header.astro',
        PageTitle: './src/components/PageTitle.astro',
        Footer: './src/components/Footer.astro',
      },
      defaultLocale: 'root',
      locales: {
        root: { label: 'English', lang: 'en' },
      },
      sidebar,
    }),
  ],
});
